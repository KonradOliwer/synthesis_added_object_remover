using System.Collections.Immutable;
using System.Diagnostics;
using System.Reflection;
using AddedObjectRemover.Run.RunAllSteps;
using AddedObjectRemover.Run.RunAllSteps.Contracts;
using AddedObjectRemover.Run.RunSettingsValidation.Contracts;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Json;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;
using Mutagen.Bethesda.Synthesis.Settings;
using Noggog;

namespace AddedObjectRemover;

public static class Program
{
    internal const string SettingsFileName = "settings.json";

    internal const string ReportsFolderName = "Reports";

    internal static readonly SettingsSchema SettingsSchema = SchemaOf(typeof(Settings));

    private static readonly SettingsSchema ConfigSchema = SchemaOf(typeof(StandardSettings));

    public static async Task<int> Main(string[] args)
    {
        using var logFile = ConsoleLogFile.StartIfRequested(ref args);
        try
        {
            return await SynthesisPipeline.Instance
                .SetAutogeneratedSettings(
                    "Settings",
                    SettingsFileName,
                    out Lazy<Settings> lazySettings)
                .AddPatch<ISkyrimMod, ISkyrimModGetter>(
                    state => RunPatch(state, () => LoadSettings(lazySettings), Environment.ProcessorCount, pluginsFile: null))
                .SetTypicalOpen(GameRelease.SkyrimSE, "AddedObjectRemover.esp")
                .Run(args);
        }
        catch (Exception ex) when (logFile != null)
        {
            logFile.WriteToFileOnly(ex.ToString());
            throw;
        }
    }

    /// <param name="loadSettings">Called after the banner, so a settings failure message follows it.</param>
    /// <param name="pluginsFile">The game's plugins file; null reads the library's default location for the game.</param>
    internal static void RunPatch(
        IPatcherState<ISkyrimMod, ISkyrimModGetter> state, Func<IModeSettingsValues> loadSettings, int workers, FilePath? pluginsFile)
    {
        var totalTimer = Stopwatch.StartNew();
        Console.WriteLine("=== Added Object Remover ===");

        var settings = loadSettings();
        var configs = ReadConfigs(settings, state.DataFolderPath.Path);
        using var world = OpenFinalWorld(state, pluginsFile);
        var pluginRecords = new PluginRecordsFactory(world, workers);
        var requests = ValidateRequests(state, settings, configs, world, pluginRecords, workers);
        var patchWriting = new PatchWriting(new SynthesisWriteCache(state.LinkCache), state.PatchMod);
        if (requests.Any(request => request is RunRequest.Ready)) patchWriting.WritePatchMarker();
        StepRunner.PatchLoadOrder(requests, CreateEnvironment(state, world, pluginRecords, patchWriting, totalTimer));
    }

    private static FinalWorld OpenFinalWorld(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, FilePath? pluginsFile)
    {
        var pluginList = PluginListReader.Read(
            state.GameRelease,
            state.DataFolderPath,
            pluginsFile,
            state.LoadOrder.ListedOrder.Select(listing => listing.ModKey),
            state.PatchMod.ModKey);
        var worlds = new FinalWorldFactory(FinalWorldFactory.ImportFromDataFolder(state.GameRelease));
        return worlds.Create(state.LoadOrder.ListedOrder, state.PatchMod, TakeListOrFail(pluginList), state.DataFolderPath);
    }

    private static ImmutableArray<RunRequest> ValidateRequests(
        IPatcherState<ISkyrimMod, ISkyrimModGetter> state,
        IModeSettingsValues settings,
        ConfigsRead configs,
        FinalWorld world,
        PluginRecordsFactory pluginRecords,
        int workers) =>
        TakeRequestsOrFail(SettingsValidator.BuildAll(
            configs,
            pluginRecords.Open(),
            world.Plugins,
            settings.DetailedLogAndReports,
            settings.OnlyWarnWhenModRequiringCleanedModLoadsAfterPatch,
            settings.DetailedLogAndReports ? ReportsFolder(state) : null,
            workers));

    private static RunEnvironment CreateEnvironment(
        IPatcherState<ISkyrimMod, ISkyrimModGetter> state, FinalWorld world, PluginRecordsFactory pluginRecords, PatchWriting patchWriting, Stopwatch totalTimer) =>
        new(
            world.Plugins,
            pluginRecords,
            patchWriting,
            new MeshFilesFactory(state.DataFolderPath.Path, state.GameRelease, [.. world.Order.ListedOrder.Select(listing => listing.ModKey)]),
            new BaseFactsFactory(world.Plugins.Mods),
            new ConsoleLogSink(),
            new CsvReportOutput(),
            () => totalTimer.Elapsed);

    /// <summary>
    /// A folder in the patcher's own data folder in Synthesis ("Data\&lt;profile&gt;\&lt;patcher name&gt;"), which lasts between runs
    /// (the output folder is wiped at the start of every run). Only a run with the detailed log and reports on needs it; a run started with arguments but without that folder fails then.
    /// </summary>
    internal static string ReportsFolder(IPatcherState<ISkyrimMod, ISkyrimModGetter> state) =>
        Path.Combine(
            state.ExtraSettingsDataPath?.Path ?? throw new InvalidOperationException("Synthesis passed no data folder for this patcher."),
            ReportsFolderName);

    /// <summary>Reads the config files with the converters Synthesis reads settings.json with, so a config file reads like the Standard group.</summary>
    internal static ConfigsRead ReadConfigs(IModeSettingsValues settings, string dataFolder) =>
        ConfigFiles.Read(settings, dataFolder, ConfigSchema, json => json.AddMutagenConverters());

    private static ImmutableArray<RunRequest> TakeRequestsOrFail(BatchRequest batch) => batch switch
    {
        BatchRequest.Ready ready => ready.Requests,
        BatchRequest.Failed failed => throw StopRun(failed),
        _ => throw new UnreachableException(),
    };

    private static PluginListRead.Found TakeListOrFail(PluginListRead pluginList) => pluginList switch
    {
        PluginListRead.Found found => found,
        PluginListRead.Failed unusable => throw StopRun(SettingsValidator.StopOnUnusablePluginList(unusable.Problem)),
        _ => throw new UnreachableException(),
    };

    private static BatchStoppedException StopRun(BatchRequest.Failed failed)
    {
        Console.Error.WriteLine(failed.Message);
        return new BatchStoppedException(failed.Message);
    }

    private static SettingsSchema SchemaOf(Type root) =>
        new(root, property => property.GetCustomAttribute<SynthesisSettingName>()?.Name, typeof(ModKey));

    private static Settings LoadSettings(Lazy<Settings> lazySettings)
    {
        try
        {
            return SettingsLoading.Load(() => lazySettings.Value, SettingsSchema, SettingsFileName);
        }
        catch (SettingsUnreadableException ex)
        {
            Console.Error.WriteLine(ex.Message);
            throw;
        }
    }
}
