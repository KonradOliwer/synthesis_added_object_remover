    private sealed record RunConfig(
        ModKey Target,
        HashSet<ModKey> IgnoredOrigins,
        IReadOnlyList<ModKey> ExcludedPlugins,
        IReadOnlyList<ModKey> TargetMasters,
        bool ExcludeTargetMasters,
        float Multiplier,
        bool UseNifBounds,
        bool SkipReferenced,
        bool Verbose);

    private static RunConfig? CreateConfig(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, Settings settings)
    {
        if (string.IsNullOrWhiteSpace(settings.TargetPlugin))
        {
            Console.WriteLine("No target plugin set. No changes made.");
            return null;
        }
        if (!ModKey.TryFromNameAndExtension(settings.TargetPlugin.Trim(), out var target))
        {
            Console.WriteLine($"Target plugin '{settings.TargetPlugin}' is not a valid plugin file name. No changes made.");
            return null;
        }
        var targetListing = state.LoadOrder.ListedOrder.FirstOrDefault(listing => listing.ModKey == target);
        if (targetListing == null)
        {
            Console.WriteLine($"Target plugin {target} is not in the load order. No changes made.");
            return null;
        }

        var ignored = new HashSet<ModKey>(BaseGamePlugins) { target, state.PatchMod.ModKey };

        var excluded = new List<ModKey>();
        foreach (var name in settings.ExcludedPlugins)
        {
            if (string.IsNullOrWhiteSpace(name)) continue;
            if (ModKey.TryFromNameAndExtension(name.Trim(), out var key))
            {
                excluded.Add(key);
                ignored.Add(key);
            }
            else
            {
                Console.WriteLine($"Warning: excluded plugin '{name}' is not a valid plugin file name and was ignored.");
            }
        }

        var masters = new List<ModKey>();
        if (settings.ExcludeTargetMasters)
        {
            if (targetListing.Mod is { } targetMod)
            {
                foreach (var master in targetMod.MasterReferences)
                {
                    masters.Add(master.Master);
                    ignored.Add(master.Master);
                }
            }
            else
            {
                Console.WriteLine($"Warning: could not read {target} to find its masters.");
            }
        }

        var multiplier = settings.Multiplier;
        if (!float.IsFinite(multiplier) || multiplier < 0)
        {
            Console.WriteLine($"Warning: multiplier {settings.Multiplier} is invalid; using 0.");
            multiplier = 0;
        }

        return new RunConfig(
            Target: target,
            IgnoredOrigins: ignored,
            ExcludedPlugins: excluded,
            TargetMasters: masters,
            ExcludeTargetMasters: settings.ExcludeTargetMasters,
            Multiplier: multiplier,
            UseNifBounds: settings.UseNifBounds,
            SkipReferenced: settings.SkipReferencedObjects,
            Verbose: settings.VerboseLogging);
    }

    private static void PrintConfig(RunConfig config)
    {
        static string Join(IReadOnlyList<ModKey> keys) => keys.Count == 0 ? "(none)" : string.Join(", ", keys);

        Console.WriteLine($"Target plugin: {config.Target}");
        Console.WriteLine($"Multiplier: {config.Multiplier}");
        Console.WriteLine($"Excluded plugins: {Join(config.ExcludedPlugins)}");
        Console.WriteLine(config.ExcludeTargetMasters
            ? $"Excluded masters of target: {Join(config.TargetMasters)}"
            : "Masters of target are not excluded.");
        Console.WriteLine($"Bounds source: {(config.UseNifBounds ? "NIF mesh, OBND fallback" : "OBND only")}");
        Console.WriteLine($"Keep referenced objects: {config.SkipReferenced}; verbose: {config.Verbose}");
    }

