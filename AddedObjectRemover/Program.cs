            $"  Meshes voxelized: {voxels.Built:N0} ({voxels.Voxels:N0} voxels, {voxels.Samples:N0} samples"
            + (voxels.Coarsened > 0 ? $", {voxels.Coarsened:N0} sampled coarser due to size" : string.Empty)
