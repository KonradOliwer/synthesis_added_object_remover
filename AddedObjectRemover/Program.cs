    private static string Describe(IMajorRecordGetter record) => Describe(record.FormKey, record.EditorID);

    private static string Describe(FormKey formKey, string? editorId) =>
        string.IsNullOrEmpty(editorId) ? formKey.ToString() : $"{editorId} [{formKey}]";

    /// <summary>
    /// Base objects are resolved through their typed base link (already cached by the bounds
    /// lookup), never through an untyped IMajorRecordGetter lookup.
    /// </summary>
    private static string DescribeBase(ObjectBoundsProvider bounds, BaseRef? baseRef)
    {
        if (baseRef is not { } reference) return "(none)";
        return bounds.TryResolveBase(reference) is { } record ? Describe(record) : reference.FormKey.ToString();
    }

    private static void LogRemoval(ObjectBoundsProvider bounds, ScanResult scan, Hit hit)
    {
        var target = hit.Target;
        var location = target.CellName == null
            ? scan.SpaceNames[target.SpaceKey]
            : $"{scan.SpaceNames[target.SpaceKey]}, cell {target.CellName}";
        Console.WriteLine(
            $"  Removed {Describe(target.Record)} (base {DescribeBase(bounds, target.Base)}) in {location}; "
            + $"too close to {Describe(hit.Other.FormKey, hit.Other.EditorId)} from {hit.Other.FormKey.ModKey}"
            + (hit.Other.WinningMod == hit.Other.FormKey.ModKey ? string.Empty : $" (winning override in {hit.Other.WinningMod})"));
    }

    private static void PrintBoundsStats(ObjectBoundsProvider bounds, bool useNif)
    {
        if (useNif)
        {
            Console.WriteLine(
                $"Bounds: {bounds.BasesFromNif:N0} bases from NIF, {bounds.BasesNifFallbackToObnd:N0} NIF misses, "
                + $"{bounds.BasesFromObnd:N0} from OBND, {bounds.BasesWithoutBounds + bounds.BasesUnresolved:N0} without bounds. "
                + $"Meshes: {bounds.ModelsRead:N0} read, {bounds.ModelsFailed:N0} failed "
                + $"({bounds.ModelsFromLooseFiles:N0} loose, {bounds.ModelsFromArchives:N0} from {bounds.ArchivesIndexed:N0} archives).");
        }
        else
        {
            Console.WriteLine(
                $"Bounds: {bounds.BasesFromObnd:N0} bases from OBND, "
                + $"{bounds.BasesWithoutBounds + bounds.BasesUnresolved:N0} without bounds.");
        }
    }

    private static void PrintSpaceSummary(
        ScanResult scan,
        IReadOnlyDictionary<FormKey, SpatialGrid<OtherObject>> grids,
        IReadOnlyList<Hit> removed)
    {
        var removedBySpace = removed
            .GroupBy(h => h.Target.SpaceKey)
            .ToDictionary(g => g.Key, g => g.Count());
        Console.WriteLine("Per cell/worldspace (target objects / other objects / removed):");
        foreach (var group in scan.Targets
                     .GroupBy(t => t.SpaceKey)
                     .OrderBy(g => scan.SpaceNames[g.Key], StringComparer.OrdinalIgnoreCase))
        {
            removedBySpace.TryGetValue(group.Key, out var removedCount);
            Console.WriteLine(
                $"  {scan.SpaceNames[group.Key]}: {group.Count():N0} / {grids[group.Key].Count:N0} / {removedCount:N0}");
        }
    }
