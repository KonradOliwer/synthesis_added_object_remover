    /// <summary>
    /// A target-plugin object that may be removed. Only plain data plus the winning context of its
    /// cell is kept; the override is written through that cell context (see <see cref="RemoveObject"/>).
    /// </summary>
    private sealed record TargetObject(
        IPlacedGetter Record,
        IModContext<ISkyrimMod, ISkyrimModGetter, ICell, ICellGetter> WinningCell,
        bool InPersistentList,
        FormKey SpaceKey,
        FormKey CellKey,
        string? CellName,
        PlacedTransform Transform,
        BaseRef? Base,
        bool IsTeleportDoor);

    /// <summary>Compact snapshot of another mod's placed object (winning version).</summary>
    private readonly record struct OtherObject(
        FormKey FormKey,
        ModKey WinningMod,
        string? EditorId,
        BaseRef? Base,
        Vector3 Position,
        P3Float Rotation,
        float Scale,
        bool IsPrimitive);

    /// <summary>A too-close target (index into ScanResult.Targets) and the first other object found.</summary>
    private readonly record struct Hit(int TargetIndex, OtherObject Other);

    /// <summary>
    /// A target object to remove (index into ScanResult.Targets): either too close to
    /// <paramref name="Other"/>, or touching the removed target <paramref name="TouchedIndex"/>.
    /// </summary>
    private sealed record Removal(int TargetIndex, OtherObject? Other, int? TouchedIndex);

    private sealed class ScanResult
    {
        public List<TargetObject> Targets { get; } = [];
        public Dictionary<FormKey, List<OtherObject>> OthersBySpace { get; } = new();
        public Dictionary<FormKey, string> SpaceNames { get; } = new();

        /// <summary>Target FormKey -> why another placed object depends on it (first reason found).</summary>
        public Dictionary<FormKey, string> TargetReferences { get; } = new();

        public int RecordsScanned { get; set; }
        public int TargetsOverriddenLater { get; set; }
        public int TargetsDisabledOrWithoutPlacement { get; set; }

        /// <summary>Other-mod objects excluded because the target plugin itself overrides them (rule 1).</summary>
        public int OthersOverriddenByTarget { get; set; }
    }

    /// <summary>
    /// Single pass over every placed record of the load order.
    ///
    /// Why this shape: Mutagen has no IPlaced case in SkyrimModCommon.EnumerateMajorRecordContexts,
    /// so enumerating IPlaced contexts falls back to InterfaceEnumerationHelper, which runs one full
    /// enumeration per implementing registration (APlacedTrap, PlacedNpc, PlacedObject): every
    /// cell tree, exterior block/subblock and (re-created) worldspace TopCell of every plugin is
    /// walked three times. Enumerating concrete types once each would still be 3+ walks (PlacedObject,
    /// PlacedNpc and each placed trap/projectile type). Instead, each mod's cell tree is walked
    /// exactly once via EnumerateMajorRecordContexts&lt;ICell, ICellGetter&gt;: for ICellGetter
    /// Mutagen yields every interior cell (CellBlocks/SubBlocks) and every worldspace TopCell and
    /// exterior cell (Blocks/SubBlocks) without descending into their children
    /// (ModContextExt: TypeMatch.Match), and this method then reads each cell's Persistent and
    /// Temporary lists itself.
    ///
    /// Mods are visited in priority order (highest first), so the first time a FormKey is seen is
    /// its winning override, exactly like Mutagen's WinningContextOverrides (a deleted winner still
    /// claims its FormKey, so an older version never takes its place). The same holds for cells:
    /// the first context seen for a cell FormKey is its winning override, which is what Mutagen's
    /// own placed-record context would resolve (linkCache.Resolve&lt;ICellGetter&gt;) before adding
    /// the override, so it is kept for cells in target spaces and used for removal.
    /// </summary>
    private static ScanResult ScanPlacedRecords(
        IPatcherState<ISkyrimMod, ISkyrimModGetter> state,
        RunConfig config,
        IReadOnlySet<FormKey> targetSpaceKeys,
        IReadOnlySet<FormKey> overriddenByTarget)
    {
        var scan = new ScanResult();
        var seenRecords = new HashSet<FormKey>();
        var winningCells = new Dictionary<FormKey, IModContext<ISkyrimMod, ISkyrimModGetter, ICell, ICellGetter>>();

        foreach (var listing in state.LoadOrder.PriorityOrder)
        {
            if (listing.Mod is not { } mod) continue;
            var modKey = listing.ModKey;

            foreach (var cellContext in mod.EnumerateMajorRecordContexts<ICell, ICellGetter>(state.LinkCache))
            {
                var cell = cellContext.Record;
                var (spaceKey, spaceRecord) = GetCellSpace(cellContext);
                var inTargetSpace = targetSpaceKeys.Contains(spaceKey);
                if (inTargetSpace) winningCells.TryAdd(cell.FormKey, cellContext);

                if (cell.Persistent.Count == 0 && cell.Temporary.Count == 0) continue;

                for (var list = 0; list < 2; list++)
                {
                    var persistent = list == 0;
                    foreach (var record in persistent ? cell.Persistent : cell.Temporary)
                    {
                        if (!seenRecords.Add(record.FormKey)) continue; // A higher-priority mod already won.
                        scan.RecordsScanned++;
                        if (record.IsDeleted) continue;

                        if (config.SkipReferenced)
                        {
                            CollectTargetReferences(record, config.Target, scan.TargetReferences);
                        }

                        var origin = record.FormKey.ModKey;
                        var isTarget = origin == config.Target;
                        if (isTarget)
                        {
                            // Only objects the target plugin still "owns": not changed by any later plugin.
                            // This also covers the patch mod itself: if an earlier patcher in the same
                            // Synthesis run already overrode this object, the winning mod is the patch
                            // mod, not the target, so it is treated the same as any other later override.
                            if (modKey != config.Target)
                            {
                                scan.TargetsOverriddenLater++;
                                continue;
                            }
                        }
                        else if (config.IgnoredOrigins.Contains(origin))
                        {
                            continue;
                        }
                        else if (overriddenByTarget.Contains(record.FormKey))
                        {
                            // The target plugin itself overrides this FormKey (its own cell tree
                            // holds a copy of it), so it is a replacement, not an "other mod" object,
                            // no matter which plugin currently wins it.
                            scan.OthersOverriddenByTarget++;
                            if (config.Verbose)
                            {
                                var winner = modKey == origin ? string.Empty : $" (winning override in {modKey})";
                                Console.WriteLine(
                                    $"  Ignored other-mod object overridden by {config.Target}: "
                                    + $"{Describe(record.FormKey, record.EditorID)} from {origin}{winner}.");
                            }
                            continue;
                        }

                        if (IsInitiallyDisabled(record)
                            || record.Placement is not { } placement
                            || !Geometry.IsWithinLimits(Geometry.ToVector(placement.Position)))
                        {
                            if (isTarget) scan.TargetsDisabledOrWithoutPlacement++;
                            continue;
                        }

                        // Neither target objects nor indexed other objects can exist outside
                        // target spaces (targets define them), so nothing else is needed there.
                        if (!inTargetSpace) continue;

                        var position = Geometry.ToVector(placement.Position);
                        var scale = NormalizeScale(record.Scale);
                        var baseRef = GetBase(record);

                        if (isTarget)
                        {
                            // Space names are only ever displayed for target objects, so the string is
                            // only built here, once per space.
                            if (!scan.SpaceNames.ContainsKey(spaceKey))
                            {
                                scan.SpaceNames[spaceKey] = BuildSpaceName(spaceRecord);
                            }

                            scan.Targets.Add(new TargetObject(
                                Record: record,
                                WinningCell: winningCells[cell.FormKey],
                                InPersistentList: persistent,
                                SpaceKey: spaceKey,
                                CellKey: cell.FormKey,
                                CellName: config.Verbose && cell.FormKey != spaceKey ? Describe(cell) : null,
                                Transform: new PlacedTransform(position, Geometry.RotationFromEuler(placement.Rotation), scale),
                                Base: baseRef,
                                IsTeleportDoor: record is IPlacedObjectGetter { TeleportDestination: not null }));
                        }
                        else
                        {
                            if (!scan.OthersBySpace.TryGetValue(spaceKey, out var others))
                            {
                                others = [];
                                scan.OthersBySpace[spaceKey] = others;
                            }
                            others.Add(new OtherObject(
                                record.FormKey,
                                modKey,
                                config.Verbose ? record.EditorID : null,
                                baseRef,
                                position,
                                placement.Rotation,
                                scale,
                                record is IPlacedObjectGetter { Primitive: not null }));
                        }
                    }
                }
            }
        }

        return scan;
    }

    private static bool IsInitiallyDisabled(IPlacedGetter record) =>
        (record.MajorRecordFlagsRaw & (int)SkyrimMajorRecord.SkyrimMajorRecordFlag.InitiallyDisabled) != 0;

    private static float NormalizeScale(float? scale) =>
        scale is { } s && float.IsFinite(s) && s > 0 ? s : 1f;

    /// <summary>
    /// Comparison space of a cell yielded by the cell enumeration: its worldspace for exterior cells
    /// (including the worldspace's persistent TopCell, whose context parent is the worldspace),
    /// otherwise the interior cell itself.
    /// </summary>
    private static (FormKey SpaceKey, IMajorRecordGetter SpaceRecord) GetCellSpace(
        IModContext<ISkyrimMod, ISkyrimModGetter, ICell, ICellGetter> cellContext)
    {
        for (var current = cellContext.Parent; current != null; current = current.Parent)
        {
            if (current.Record is IWorldspaceGetter worldspace)
            {
                return (worldspace.FormKey, worldspace);
            }
        }
        return (cellContext.Record.FormKey, cellContext.Record);
    }

    private static string BuildSpaceName(IMajorRecordGetter spaceRecord) => spaceRecord switch
    {
        IWorldspaceGetter worldspace => $"worldspace {Describe(worldspace)}",
        ICellGetter cell => $"interior {Describe(cell)}",
        _ => Describe(spaceRecord),
    };

    /// <summary>
    /// Result of <see cref="CollectTargetSpaceKeys"/>: the spaces that can contain a target object,
    /// plus the FormKeys of every placed record the target plugin itself overrides (a record present
    /// in the target plugin's own cell tree whose FormKey originates from another plugin).
    /// </summary>
    private sealed record TargetSpaceInfo(HashSet<FormKey> SpaceKeys, HashSet<FormKey> OverriddenByTarget);

    /// <summary>
    /// Cheaply collects the set of spaces (worldspace or interior cell FormKeys) that contain at
    /// least one placed record created by the target plugin, by walking only the target plugin's
    /// own cell tree once. Used to avoid indexing other mods' objects in spaces that can never
    /// contain a target object. The same pass also collects every FormKey the target plugin
    /// overrides (regardless of which plugin ends up winning it), so such records are never treated
    /// as "other mods'" objects: the target plugin replaced them itself.
    /// </summary>
    private static TargetSpaceInfo CollectTargetSpaceKeys(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, ModKey target)
    {
        var keys = new HashSet<FormKey>();
        var overridden = new HashSet<FormKey>();
        var listing = state.LoadOrder.ListedOrder.FirstOrDefault(l => l.ModKey == target);
        if (listing?.Mod is not { } mod) return new TargetSpaceInfo(keys, overridden);

        foreach (var cellContext in mod.EnumerateMajorRecordContexts<ICell, ICellGetter>(state.LinkCache))
        {
            var cell = cellContext.Record;
            var hasTargetRecord = false;
            for (var list = 0; list < 2; list++)
            {
                foreach (var record in list == 0 ? cell.Persistent : cell.Temporary)
                {
                    if (record.FormKey.ModKey == target)
                    {
                        hasTargetRecord = true;
                    }
                    else
                    {
                        overridden.Add(record.FormKey);
                    }
                }
            }
            if (hasTargetRecord)
            {
                keys.Add(GetCellSpace(cellContext).SpaceKey);
            }
        }
        return new TargetSpaceInfo(keys, overridden);
    }

    /// <summary>Base object of any placed record type, with the base link's own record type.</summary>
    private static BaseRef? GetBase(IPlacedGetter record) => record switch
    {
        IPlacedObjectGetter placedObject => ToBaseRef(placedObject.Base),
        IPlacedNpcGetter placedNpc => ToBaseRef(placedNpc.Base),
        IPlacedHazardGetter hazard => ToBaseRef(hazard.Hazard),
        IPlacedArrowGetter arrow => ToBaseRef(arrow.Projectile),
        IPlacedBarrierGetter barrier => ToBaseRef(barrier.Projectile),
        IPlacedBeamGetter beam => ToBaseRef(beam.Projectile),
        IPlacedConeGetter cone => ToBaseRef(cone.Projectile),
        IPlacedFlameGetter flame => ToBaseRef(flame.Projectile),
        IPlacedMissileGetter missile => ToBaseRef(missile.Projectile),
        IPlacedTrapGetter trap => ToBaseRef(trap.Projectile),
        _ => null,
    };

    /// <summary>
    /// <typeparamref name="TGetter"/> is the link's declared target type (e.g. IPlaceableObjectGetter,
    /// INpcGetter, IHazardGetter, IProjectileGetter), used later for narrowly typed resolution.
    /// </summary>
    private static BaseRef? ToBaseRef<TGetter>(IFormLinkGetter<TGetter> link)
        where TGetter : class, IMajorRecordGetter =>
        link.IsNull ? null : new BaseRef(link.FormKey, typeof(TGetter));

    private static FormKey? LinkKey(IFormLinkGetter link) => link.IsNull ? null : link.FormKey;

    /// <summary>
    /// Records target-plugin objects that this record depends on: as Enable Parent, Linked
    /// Reference, Activate Parent, destination of its door teleport, or through any other form
    /// link of the record. Links to non-placed records are recorded too but never looked up.
    /// </summary>
    private static void CollectTargetReferences(IPlacedGetter record, ModKey target, Dictionary<FormKey, string> references)
    {
        void Add(IFormLinkGetter link, string relation)
        {
            if (LinkKey(link) is not { } key || key.ModKey != target || key == record.FormKey) return;
            if (references.ContainsKey(key)) return;
            references[key] = $"{relation} of {record.FormKey}";
        }

        if (record.EnableParent is { } enableParent)
        {
            Add(enableParent.Reference, "Enable Parent");
        }

        IReadOnlyList<ILinkedReferencesGetter>? linkedReferences = record switch
        {
            IPlacedObjectGetter placedObject => placedObject.LinkedReferences,
            IPlacedNpcGetter placedNpc => placedNpc.LinkedReferences,
            IAPlacedTrapGetter placedTrap => placedTrap.LinkedReferences,
            _ => null,
        };
        if (linkedReferences != null)
        {
            foreach (var linked in linkedReferences)
            {
                Add(linked.Reference, "Linked Reference");
            }
        }

        if (record is IPlacedObjectGetter { TeleportDestination: { } destination })
        {
            Add(destination.Door, "teleport destination of door");
        }

        var activateParents = record switch
        {
            IPlacedObjectGetter placedObject => placedObject.ActivateParents,
            IPlacedNpcGetter placedNpc => placedNpc.ActivateParents,
            IAPlacedTrapGetter placedTrap => placedTrap.ActivateParents,
            _ => null,
        };
        if (activateParents != null)
        {
            foreach (var parent in activateParents.Parents)
            {
                Add(parent.Reference, "Activate Parent");
            }
        }

        foreach (var link in record.EnumerateFormLinks())
        {
            Add(link, "referenced by a link");
        }
    }

